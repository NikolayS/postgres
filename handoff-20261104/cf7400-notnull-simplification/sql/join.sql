set enable_partitionwise_join = on;
CREATE FUNCTION jf(varchar) RETURNS varchar LANGUAGE sql IMMUTABLE AS 'SELECT $1';
CREATE TABLE j1 (a varchar(3), b varchar(3)) PARTITION BY LIST ((COALESCE(jf(a), b)));
CREATE TABLE j1a PARTITION OF j1 FOR VALUES IN ('a');
CREATE TABLE j1b PARTITION OF j1 FOR VALUES IN ('b');
CREATE TABLE j2 (a varchar(3), b varchar(3)) PARTITION BY LIST ((CASE WHEN a IS NOT NULL THEN jf(a) ELSE b END));
CREATE TABLE j2a PARTITION OF j2 FOR VALUES IN ('a');
CREATE TABLE j2b PARTITION OF j2 FOR VALUES IN ('b');
CREATE TABLE j3 (a varchar(3), b varchar(3)) PARTITION BY LIST ((COALESCE(jf(a), b)));
CREATE TABLE j3a PARTITION OF j3 FOR VALUES IN ('a');
CREATE TABLE j3b PARTITION OF j3 FOR VALUES IN ('b');
EXPLAIN (COSTS OFF) SELECT * FROM j1 JOIN j3 ON COALESCE(jf(j1.a), j1.b) = COALESCE(jf(j3.a), j3.b);
EXPLAIN (COSTS OFF) SELECT * FROM j2 JOIN j2 x ON (CASE WHEN j2.a IS NOT NULL THEN jf(j2.a) ELSE j2.b END) = (CASE WHEN x.a IS NOT NULL THEN jf(x.a) ELSE x.b END);
